/** 营收 → 纵坐标：对数刻度，从 0.05 亿到 8809 亿跨 5.2 个数量级，每十倍 128px */
export const CAP_FLOOR = 0.05;
export const capY = (v: number) => 830 - 128 * (Math.log10(v) - Math.log10(CAP_FLOOR));

export const CAP_PTS: [number, number][] = CAP.map(([y, v]) => [yx(y), capY(v)]);

/** 某个横坐标处命运线的高度 */
export const capAt = (x: number) => lerp(CAP_PTS, x, 0);
