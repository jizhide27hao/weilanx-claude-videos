/** 市值 → 纵坐标：对数刻度，一个十倍 260px，地板 20 亿美元 */
export const CAP_FLOOR = 20;
export const capY = (v: number) => 880 - 260 * (Math.log10(v) - Math.log10(CAP_FLOOR));

export const CAP_PTS: [number, number][] = CAP.map(([y, v]) => [yx(y), capY(v)]);

/** 某个横坐标处命运线的高度（线性内插 CAP_PTS） */
export const capAt = (x: number) => {
  const pts = CAP_PTS;
  if (x <= pts[0][0]) return pts[0][1];
  for (let i = 1; i < pts.length; i++) if (x <= pts[i][0]) return pts[i - 1][1] + ((x - pts[i - 1][0]) / (pts[i][0] - pts[i - 1][0])) * (pts[i][1] - pts[i - 1][1]);
  return pts[pts.length - 1][1];
};
