/** 市值 → 纵坐标：对数刻度，2000 亿落在 820，一个十倍 340px */
export const CAP_FLOOR = 2000;
export const capY = (v: number) => 820 - 340 * (Math.log10(v) - Math.log10(CAP_FLOOR));

export const CAP_PTS: [number, number][] = CAP.map(([y, v]) => [yx(y), capY(v)]);

/** 某个横坐标处命运线的高度 */
export const capAt = (x: number) => lerp(CAP_PTS, x, 0);
