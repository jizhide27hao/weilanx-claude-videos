/** 市值 → 纵坐标：对数刻度，一个十倍 118px */
export const CAP_FLOOR = 10;
export const capY = (v: number) => 860 - 118 * (Math.log10(v) - Math.log10(CAP_FLOOR));

export const CAP_PTS: [number, number][] = CAP.map(([y, v]) => [yx(y), capY(v)]);

/** 某个横坐标处命运线的高度 */
export const capAt = (x: number) => lerp(CAP_PTS, x, 0);
